def normalize_language(value: object) -> str:
    return value if isinstance(value, str) and value in SUPPORTED_LANGUAGES else "zh"


def contains_cjk(text: str) -> bool:
    return bool(_CJK_RE.search(text))


def translate_text(text: str, language: str) -> str:
    target = normalize_language(language)
    if not text or target == "zh":
        return text
    exact = EN_TRANSLATIONS.get(text)
    if exact is not None:
        return exact
    for source, translated in sorted(EN_TRANSLATIONS.items(), key=lambda item: len(item[0]), reverse=True):
        if source in _EXACT_ONLY_KEYS:
            continue
        if source in text:
            text = text.replace(source, translated)
    return text
